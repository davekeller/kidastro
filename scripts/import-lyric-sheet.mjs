#!/usr/bin/env node
// Import Paper Fang lyric-sheet HTML files (the Dropbox template format) into
// typed song data files under data/lyrics/songs/, then regenerate
// data/lyrics/index.ts.
//
//   node scripts/import-lyric-sheet.mjs <sheet.html | dir> [...more]
//
// The sheet format: <h1>Title</h1>, <p class="artist">Artist</p>, then
// .section blocks each holding a .section-header ("[Verse 1]") and a .lyrics
// div of <p> lines. A <p> of only &nbsp; is a stanza gap; class="placeholder"
// marks an empty/instrumental section.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SONGS_DIR = path.join(ROOT, 'data', 'lyrics', 'songs');
const INDEX_PATH = path.join(ROOT, 'data', 'lyrics', 'index.ts');
const HOME_ARTIST = 'paper fang';

const decode = (s) =>
  s
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;/g, "'")
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)));

const clean = (s) => decode(s).replace(/\s+/g, ' ').trim();

const slugify = (title) =>
  title
    .normalize('NFKD')
    .replace(/ø/g, 'o') // ø doesn't decompose via NFKD
    .replace(/Ø/g, 'o')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

function parseSheet(html) {
  const title = clean((html.match(/<h1>([\s\S]*?)<\/h1>/) || [])[1] || '')
    .replace(/<span class="badge">[\s\S]*?<\/span>/, '')
    .trim();
  if (!title) throw new Error('no <h1> title found');

  const artist = clean((html.match(/<p class="artist">([\s\S]*?)<\/p>/) || [])[1] || '');

  const sections = [];
  const sectionRe = /<div class="section">([\s\S]*?)<\/div>\s*<\/div>/g;
  for (const [, block] of html.matchAll(sectionRe)) {
    const label = clean((block.match(/<div class="section-header">([\s\S]*?)<\/div>/) || [])[1] || '')
      .replace(/^\[|\]$/g, '');
    const lines = [];
    const pRe = /<p(\s[^>]*)?>([\s\S]*?)<\/p>/g;
    for (const [, attrs = '', inner] of block.matchAll(pRe)) {
      if (/placeholder/.test(attrs)) continue; // "· · ·" empty-section marker
      const text = clean(inner.replace(/<[^>]+>/g, ''));
      lines.push(text === '' || text === '·' ? '' : text);
    }
    // Trim leading/trailing stanza gaps and collapse doubles.
    const trimmed = lines
      .filter((l, i) => !(l === '' && (lines[i - 1] ?? '') === ''))
      .filter((l, i, a) => !(l === '' && (i === 0 || i === a.length - 1)));
    sections.push({ label, lines: trimmed });
  }
  if (!sections.length) throw new Error('no sections found');

  const hasLyrics = sections.some((s) => s.lines.length > 0);
  return {
    slug: slugify(title),
    title,
    ...(artist && artist.toLowerCase() !== HOME_ARTIST ? { cover: { artist } } : {}),
    status: hasLyrics ? 'ready' : 'in-progress',
    sections,
  };
}

function writeSong(song) {
  const body = JSON.stringify(song, null, 2).replace(/"([a-zA-Z_]\w*)":/g, '$1:');
  const src = `import type { Song } from '../types';

const song: Song = ${body};

export default song;
`;
  fs.mkdirSync(SONGS_DIR, { recursive: true });
  fs.writeFileSync(path.join(SONGS_DIR, `${song.slug}.ts`), src);
  return song.slug;
}

function regenerateIndex() {
  const slugs = fs
    .readdirSync(SONGS_DIR)
    .filter((f) => f.endsWith('.ts'))
    .map((f) => f.replace(/\.ts$/, ''))
    .sort();
  const ident = (slug) => slug.replace(/-(\w)/g, (_, c) => c.toUpperCase());
  const src = `// Generated by scripts/import-lyric-sheet.mjs — edit song files, then re-run
// the script (or update imports by hand) when adding songs.
import type { Song } from './types';
${slugs.map((s) => `import ${ident(s)} from './songs/${s}';`).join('\n')}

export const SONGS: Song[] = [
${slugs.map((s) => `  ${ident(s)},`).join('\n')}
];

export const songBySlug = (slug: string): Song | undefined =>
  SONGS.find((s) => s.slug === slug);

export * from './types';
export { SETLISTS, DEFAULT_SETLIST_ID } from './setlists';
`;
  fs.writeFileSync(INDEX_PATH, src);
}

const args = process.argv.slice(2);
if (!args.length) {
  console.error('usage: node scripts/import-lyric-sheet.mjs <sheet.html | dir> [...more]');
  process.exit(1);
}

const files = args.flatMap((a) => {
  const st = fs.statSync(a);
  return st.isDirectory()
    ? fs.readdirSync(a).filter((f) => f.endsWith('.html')).map((f) => path.join(a, f))
    : [a];
});

for (const file of files) {
  const song = parseSheet(fs.readFileSync(file, 'utf8'));
  writeSong(song);
  const lineCount = song.sections.reduce((n, s) => n + s.lines.filter(Boolean).length, 0);
  console.log(
    `${song.slug}: ${song.sections.length} sections, ${lineCount} lines` +
      (song.cover ? ` (cover: ${song.cover.artist})` : '') +
      (song.status === 'in-progress' ? ' [in progress]' : ''),
  );
}
regenerateIndex();
console.log('index regenerated');
